import { pbkdf2Sync, randomBytes } from "node:crypto";
import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const password = process.env.XINGXUN_SETUP_PASSWORD;
const username = (process.env.XINGXUN_SETUP_USERNAME || "admin").trim();
const displayName = (process.env.XINGXUN_SETUP_DISPLAY_NAME || "管理员").trim();
const iterations = 310_000;

if (!password) {
  console.error("缺少 XINGXUN_SETUP_PASSWORD。请仅在当前终端临时设置后重试。");
  process.exit(1);
}
if (!username || password.length < 6) {
  console.error("管理员账号不能为空，密码至少需要 6 位。");
  process.exit(1);
}

const salt = randomBytes(20);
const hash = pbkdf2Sync(password, salt, iterations, 32, "sha1");
const config = {
  version: 1,
  username,
  displayName,
  passwordAlgorithm: "pbkdf2-sha1",
  passwordIterations: iterations,
  passwordSalt: salt.toString("base64url"),
  passwordHash: hash.toString("base64url"),
  sessionSecret: randomBytes(32).toString("base64url"),
  sessionVersion: 1,
};

async function writeAtomic(target, content) {
  await mkdir(path.dirname(target), { recursive: true });
  const temporary = `${target}.${process.pid}.tmp`;
  await writeFile(temporary, content, { encoding: "utf8", mode: 0o600 });
  await rename(temporary, target);
}

await writeAtomic(
  path.join(root, "data", "local-auth.json"),
  `${JSON.stringify(config, null, 2)}\n`,
);
await writeAtomic(
  path.join(root, "android", "auth.properties"),
  [
    `username=${username}`,
    `displayName=${Buffer.from(displayName, "utf8").toString("base64")}`,
    `iterations=${iterations}`,
    `salt=${config.passwordSalt}`,
    `hash=${config.passwordHash}`,
    "",
  ].join("\n"),
);

const envPath = path.join(root, ".env.local");
const authEnv = {
  LOCAL_AUTH_USERNAME: username,
  LOCAL_AUTH_DISPLAY_NAME: displayName,
  LOCAL_AUTH_PASSWORD_ITERATIONS: String(iterations),
  LOCAL_AUTH_PASSWORD_SALT: config.passwordSalt,
  LOCAL_AUTH_PASSWORD_HASH: config.passwordHash,
  LOCAL_AUTH_SESSION_SECRET: config.sessionSecret,
  LOCAL_AUTH_SESSION_VERSION: String(config.sessionVersion),
};
const authKeys = new Set(Object.keys(authEnv));
let existingEnv = "";
try {
  existingEnv = await readFile(envPath, "utf8");
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}
const preservedLines = existingEnv
  .split(/\r?\n/)
  .filter((line) => !authKeys.has(line.slice(0, line.indexOf("="))));
while (preservedLines.length && preservedLines.at(-1) === "") preservedLines.pop();
const nextEnv = [
  ...preservedLines,
  preservedLines.length ? "" : null,
  "# Local demonstration login (generated by npm run auth:setup)",
  ...Object.entries(authEnv).map(([key, value]) => `${key}=${value}`),
  "",
].filter((line) => line !== null).join("\n");
await writeAtomic(envPath, nextEnv);

console.log("本地演示登录已初始化；密码原文未写入项目文件。");
